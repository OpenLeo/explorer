export function txSnippets(frame, bytes, opts = {}) {
  const iface = opts.iface || 'can0';
  const hexs = bytesToHex(bytes, '');
  const arr = Array.from(bytes, (b) => '0x' + hexByte(b));
  const idw = frame.extended ? 8 : 3;
  const id = hex(frame.id, idw);
  const out = [];
  const period = frame.periodMs;
  if (frame.type === 'can' || frame.type === 'can-tp') {
    if (frame.type === 'can-tp' && bytes.length > 7) {
      out.push({ title: 'Note', lang: 'text', code: `This is an ISO-TP payload (${bytes.length} bytes): it must be segmented (first frame + consecutive frames, waiting for the flow control).\nUse the Diagnostics > ISO-TP builder, or on Linux: isotpsend -s ${id} -d ${frame.isotp && frame.isotp.flow_control_id !== undefined ? hex(frame.isotp.flow_control_id, 3) : '<fc id>'} ${iface}` });
    }
    out.push({ title: 'can-utils (Linux SocketCAN)', lang: 'sh', code: `cansend ${iface} ${id}#${hexs}${period ? `\n# periodic (every ${period} ms):\ncangen ${iface} -g ${period} -I ${id} -L ${bytes.length} -D ${hexs} -n 0` : ''}` });
    out.push({ title: 'candump -L / log line', lang: 'text', code: `(0.000000) ${iface} ${id}#${hexs}` });
    out.push({ title: 'SavvyCAN / GVRET CSV line', lang: 'text', code: `Time Stamp,ID,Extended,Dir,Bus,LEN,D1,D2,D3,D4,D5,D6,D7,D8\n0,${hex(frame.id, 8)},${frame.extended ? 'true' : 'false'},Tx,0,${bytes.length},${Array.from(bytes, hexByte).join(',')}` });
    out.push({ title: 'python-can', lang: 'python', code: `import can\nbus = can.Bus(channel='${iface}', interface='socketcan')\nmsg = can.Message(arbitration_id=0x${id}, is_extended_id=${frame.extended ? 'True' : 'False'}, data=bytes.fromhex('${hexs}'))\n${period ? `task = bus.send_periodic(msg, ${period / 1000})  # every ${period} ms` : 'bus.send(msg)'}` });
    out.push({ title: 'Arduino + MCP2515 (autowp/arduino-mcp2515)', lang: 'c', code: `#include <mcp2515.h>\nMCP2515 mcp2515(10);  // CS pin\nstruct can_frame f;\n\nvoid setup() {\n  mcp2515.reset();\n  mcp2515.setBitrate(${opts.bitrate === 500 ? 'CAN_500KBPS' : opts.bitrate === 125 ? 'CAN_125KBPS' : opts.bitrate ? `CAN_${opts.bitrate}KBPS` : 'CAN_125KBPS'}, MCP_8MHZ);  // check your crystal\n  mcp2515.setNormalMode();\n}\n\nvoid loop() {\n  f.can_id  = 0x${id}${frame.extended ? ' | CAN_EFF_FLAG' : ''};\n  f.can_dlc = ${bytes.length};\n  const uint8_t data[] = {${arr.join(', ')}};\n  memcpy(f.data, data, sizeof(data));\n  mcp2515.sendMessage(&f);\n  delay(${period || 100});\n}` });
    out.push({ title: 'ESP32 TWAI (ESP-IDF / Arduino-ESP32)', lang: 'c', code: `#include "driver/twai.h"\n// setup: twai_driver_install(&g_config, &${opts.bitrate === 500 ? 'TWAI_TIMING_CONFIG_500KBITS()' : opts.bitrate === 125 || !opts.bitrate ? 'TWAI_TIMING_CONFIG_125KBITS()' : `TWAI_TIMING_CONFIG_${opts.bitrate}KBITS()`}, &f_config); twai_start();\ntwai_message_t msg = {0};\nmsg.identifier = 0x${id};\nmsg.extd = ${frame.extended ? 1 : 0};\nmsg.data_length_code = ${bytes.length};\nconst uint8_t data[] = {${arr.join(', ')}};\nmemcpy(msg.data, data, sizeof(data));\ntwai_transmit(&msg, pdMS_TO_TICKS(10));${period ? `  // repeat every ${period} ms` : ''}` });
  } else if (frame.type === 'van') {
    const access = frame.van && frame.van.access || 'write';
    out.push({ title: 'VAN', lang: 'text', code: `VAN frame: IDEN 0x${hex(frame.id, 3)}, ${bytes.length} data bytes: ${bytesToHex(bytes)}\nCOM field: EXT=1 RAK=${frame.van && frame.van.ack ? 1 : 0} R/W=${access === 'read' ? 1 : 0} RTR=${frame.van && frame.van.rtr ? 1 : 0}\nVAN is not CAN: you need a VAN controller (TSS463/TSS461) or a software VAN implementation,\neg. ESP32 + SN65HVD230 transceiver with morcibacsi's esp32_rmt_van_rx (receive) / esp32_arduino_van_writer (transmit).` });
    out.push({ title: 'Arduino (morcibacsi VAN writer, pseudo code)', lang: 'c', code: `uint8_t data[] = {${arr.join(', ')}};\n// van_writer.send_frame(0x${hex(frame.id, 3)}, data, ${bytes.length}, /*require_ack=*/${frame.van && frame.van.ack ? 'true' : 'false'});` });
  } else if (frame.type === 'lin') {
    const pid = linPid(frame.id);
    const enhanced = !(frame.lin && frame.lin.checksum === 'classic');
    const cs = linChecksum(bytes, enhanced ? pid : null);
    out.push({ title: 'LIN', lang: 'text', code: `LIN frame id 0x${hex(frame.id, 2)} -> protected id (PID) 0x${hexByte(pid)}\nOn the wire: BREAK SYNC(0x55) PID(0x${hexByte(pid)}) | ${bytesToHex(bytes)} | checksum 0x${hexByte(cs)} (${enhanced ? 'enhanced, LIN 2.x' : 'classic, LIN 1.x'})\nThe master sends the header; the slave that publishes this frame sends data + checksum.` });
    out.push({ title: 'Arduino LIN (raw UART, pseudo code)', lang: 'c', code: `// break: hold TX low >= 13 bits (eg. Serial.begin(9600); write(0x00); then back to 19200)\nuint8_t frame[] = {0x55, 0x${hexByte(pid)}, ${arr.join(', ')}, 0x${hexByte(cs)}};\nSerial1.write(frame, sizeof(frame));` });
  }
  return out;
}
