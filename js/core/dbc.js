// DBC and JSON export.

import { dbcMotorolaStart, dbcIntelStart } from './bits.js';
import { ml, ident, fmtNum } from './util.js';

const DBC_HEADER = `VERSION ""


NS_ :
	NS_DESC_
	CM_
	BA_DEF_
	BA_
	VAL_
	CAT_DEF_
	CAT_
	FILTER
	BA_DEF_DEF_
	EV_DATA_
	ENVVAR_DATA_
	SGTYPE_
	SGTYPE_VAL_
	BA_DEF_SGTYPE_
	BA_SGTYPE_
	SIG_TYPE_REF_
	VAL_TABLE_
	SIG_GROUP_
	SIG_VALTYPE_
	SIGTYPE_VALTYPE_
	BO_TX_BU_
	BA_DEF_REL_
	BA_REL_
	BA_DEF_DEF_REL_
	BU_SG_REL_
	BU_EV_REL_
	BU_BO_REL_
	SG_MUL_VAL_

BS_:
`;

/** DBC strings cannot contain double quotes; keep them on one line. */
export function dbcString(s) {
  return String(s ?? '').replace(/"/g, "'").replace(/\\/g, '/').replace(/\r?\n/g, ' ').trim();
}

/** Raw range of a signal -> physical [min, max] */
export function physRange(sig, width = sig.width) {
  let lo;
  let hi;
  if (sig.type === 'sint') { lo = -(2 ** (width - 1)); hi = 2 ** (width - 1) - 1; } else { lo = 0; hi = 2 ** width - 1; }
  const a = lo * sig.factor + sig.offset;
  const b = hi * sig.factor + sig.offset;
  return [Math.min(a, b), Math.max(a, b)];
}

/** Number without exponent notation (some DBC parsers do not accept 1e+32) */
function dnum(v) {
  const s = fmtNum(v, 10);
  if (!/e/i.test(s)) return s;
  return Number(v).toLocaleString('en-US', { useGrouping: false, maximumFractionDigits: 12 });
}

function dbcId(f) { return f.extended ? (f.id | 0) + 0x80000000 : f.id; }

/**
 * Export frames to DBC.
 * opts: { lang, includeUnused, busLabel, nodes: [names] }
 * Returns { text, skipped: [{frame, reason}], warnings: [] }
 */
export function exportDbc(frames, opts = {}) {
  const lang = opts.lang || 'en';
  const includeUnused = !!opts.includeUnused;
  const skipped = [];
  const warnings = [];
  const seenIds = new Map();
  const list = [];
  for (const f of frames) {
    if (f.id < 0) { skipped.push({ frame: f, reason: 'no id' }); continue; }
    const k = dbcId(f);
    if (seenIds.has(k)) { skipped.push({ frame: f, reason: `duplicate id 0x${f.id.toString(16).toUpperCase()} (same as ${seenIds.get(k).name})` }); continue; }
    seenIds.set(k, f);
    list.push(f);
  }
  const nodes = new Set(opts.nodes || []);
  for (const f of list) { for (const n of f.senders) nodes.add(ident(n)); for (const n of f.receivers) nodes.add(ident(n)); }
  const lines = [DBC_HEADER];
  lines.push(`BU_: ${[...nodes].map((n) => ident(n)).join(' ')}`);
  lines.push('');
  const cm = [];
  const ba = [];
  const val = [];
  const mul = [];
  const valtype = [];
  const txbu = [];
  if (opts.busLabel) cm.push(`CM_ "${dbcString(opts.busLabel)} - generated by OpenLEO Explorer from DBMUXEv data (unofficial, use at your own risk)";`);
  const frameNames = new Set();
  for (const f of list) {
    const id = dbcId(f);
    let fname = ident(f.name, `FRAME_${f.idHex}`);
    if (frameNames.has(fname)) fname = `${fname}_${f.idHex}`;
    frameNames.add(fname);
    const sender = f.senders.length ? ident(f.senders[0]) : 'Vector__XXX';
    const len = f.type === 'can-tp' ? Math.min(f.length || 8, 4095) : (f.length || 0);
    lines.push(`BO_ ${id} ${fname}: ${len} ${sender}`);
    if (f.senders.length > 1) txbu.push(`BO_TX_BU_ ${id} : ${f.senders.map((s) => ident(s)).join(',')};`);
    const recv = f.receivers.length ? f.receivers.map((r) => ident(r)).join(',') : 'Vector__XXX';
    const sigNames = new Set();
    for (const s of f.signals) {
      if (!s.pos) continue;
      if (s.unused && !includeUnused) continue;
      const width = s.pos.toEnd ? Math.max(1, len * 8 - s.pos.start) : s.width;
      if (width > 64 || s.type === 'str' || s.type === 'bytes') {
        if (width > 64) { warnings.push(`${f.idHex} ${f.name}.${s.name}: ${width} bits, not representable in DBC`); continue; }
      }
      let sname = ident(s.name, 'SIG');
      if (sigNames.has(sname)) sname = `${sname}_${sigNames.size}`;
      sigNames.add(sname);
      let mux = '';
      if (s.muxSelector) mux = ' M';
      else if (s.mux && s.mux.values.length) mux = ` m${s.mux.values[0]}`;
      const sign = s.type === 'sint' ? '-' : '+';
      let startBit = dbcMotorolaStart(s.pos);
      let order = '0';
      if (s.littleEndian) {
        const ib = dbcIntelStart(s.pos);
        if (ib === null) { warnings.push(`${f.idHex} ${f.name}.${s.name}: little endian field not byte aligned, not representable in DBC`); continue; }
        startBit = ib;
        order = '1';
      }
      let [mn, mx] = physRange(s, width);
      if (s.min !== null) mn = s.min;
      if (s.max !== null) mx = s.max;
      const unit = dbcString(s.units);
      lines.push(` SG_ ${sname}${mux} : ${startBit}|${width}@${order}${sign} (${dnum(s.factor)},${dnum(s.offset)}) [${dnum(mn)}|${dnum(mx)}] "${unit}" ${s.receivers && s.receivers.length ? s.receivers.map((r) => ident(r)).join(',') : recv}`);
      const c = ml(s.comment, lang);
      if (c) cm.push(`CM_ SG_ ${id} ${sname} "${dbcString(c)}";`);
      if (s.values.length) {
        const vals = s.values.filter((v) => !(v.unused && !v.text)).map((v) => `${v.raw} "${dbcString(ml(v.text, lang) || (v.unused ? 'unused' : String(v.raw)))}"`);
        if (vals.length) val.push(`VAL_ ${id} ${sname} ${vals.join(' ')} ;`);
      }
      if (s.mux && s.mux.values.length > 1) {
        mul.push(`SG_MUL_VAL_ ${id} ${sname} ${ident(s.mux.selector)} ${s.mux.values.map((v) => `${v}-${v}`).join(', ')};`);
      }
      if (s.type === 'float' && (width === 32 || width === 64)) valtype.push(`SIG_VALTYPE_ ${id} ${sname} : ${width === 32 ? 1 : 2};`);
    }
    lines.push('');
    const fc = [ml(f.comment, lang), ml(f.observations, lang)].filter(Boolean).join(' / ');
    const extra = f.type === 'van' ? ' [VAN frame, 12 bit identifier]' : f.type === 'lin' ? ' [LIN frame]' : f.type === 'can-tp' ? ' [ISO-TP payload]' : '';
    if (fc || extra) cm.push(`CM_ BO_ ${id} "${dbcString(fc + extra)}";`);
    if (f.periodMs) ba.push(`BA_ "GenMsgCycleTime" BO_ ${id} ${f.periodMs};`);
    ba.push(`BA_ "GenMsgSendType" BO_ ${id} ${f.periodMs && f.trigger ? 2 : f.periodMs ? 0 : 1};`);
    if (f.extended) ba.push(`BA_ "VFrameFormat" BO_ ${id} 1;`);
  }
  lines.push(...txbu);
  if (txbu.length) lines.push('');
  lines.push(...cm);
  lines.push('BA_DEF_ BO_ "GenMsgCycleTime" INT 0 65535;');
  lines.push('BA_DEF_ BO_ "GenMsgSendType" ENUM "Cyclic","Event","CyclicAndEvent";');
  lines.push('BA_DEF_ BO_ "VFrameFormat" ENUM "StandardCAN","ExtendedCAN";');
  lines.push('BA_DEF_ "BusType" STRING ;');
  lines.push('BA_DEF_DEF_ "GenMsgCycleTime" 0;');
  lines.push('BA_DEF_DEF_ "GenMsgSendType" "Event";');
  lines.push('BA_DEF_DEF_ "VFrameFormat" "StandardCAN";');
  lines.push('BA_DEF_DEF_ "BusType" "CAN";');
  lines.push(...ba);
  lines.push(...val);
  lines.push(...valtype);
  lines.push(...mul);
  lines.push('');
  return { text: lines.join('\n'), skipped, warnings };
}

/** JSON export: original documents + placement metadata (lossless). */
export function exportJson(frames, extra = {}) {
  return JSON.stringify({
    generator: 'OpenLEO Explorer',
    format: 'DBMUXEv v0.2 documents',
    ...extra,
    frames: frames.map((f) => ({
      key: f.key, architecture: f.archvar, bus: f.netbus, source: f.source, path: f.path,
      normalized: {
        id: f.id, name: f.name, type: f.type, length: f.length, periodicity: f.periodicity, senders: f.senders, receivers: f.receivers,
        signals: f.signals.map((s) => ({
          name: s.name, bits: s.bits, type: s.type, factor: s.factor, offset: s.offset, min: s.min, max: s.max, units: s.units,
          invalid: s.invalid, default: s.default, unused: s.unused, byte_order: s.littleEndian ? 'little_endian' : undefined, receivers: s.receivers && s.receivers.length ? s.receivers : undefined, mux_selector: s.muxSelector || undefined, mux: s.mux || undefined,
          values: s.values.length ? Object.fromEntries(s.values.map((v) => [v.raw, v.text || { unused: true }])) : undefined,
          comment: s.comment || undefined,
        })),
      },
      document: f.raw,
    })),
  }, (k, v) => (typeof v === 'bigint' ? v.toString() : v), 1);
}
